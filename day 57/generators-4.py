##3 generators function


# A generator is a special type of function that:
# Returns values one by one
# Instead of returning everything at once
# Uses the keyword yield instead of return



# Simple Way to Think About It

# return → “Here is the final answer. I’m done.”
# yield → “Here’s one value. I’ll give you more later.”


# . yield (Generator Functions)

# Turns the function into a generator.
# Produces a value without ending the function.
# Pauses execution and remembers its state.
# Continues from where it left off when asked for the next value.